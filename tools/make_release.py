def tester_readme():
    sys.path.insert(0, ROOT)
    from game.tester import LABEL
    return TESTER_TXT.replace('@LABEL@', LABEL)


def main():
    if '--no-build' not in sys.argv:
        shutil.rmtree(os.path.join(ROOT, 'build'), ignore_errors=True)
        env = dict(os.environ)
        env.pop('DD_TESTER', None)
        if TESTER:
            env['DD_TESTER'] = '1'
        subprocess.check_call([sys.executable, 'setup.py', 'build_apps'], cwd=ROOT, env=env)
    exe = os.path.join(BUILD, APP + '.exe')
    if not os.path.isfile(exe):
        sys.exit('не найден %s — сначала выполните сборку' % exe)
    with open(exe, 'rb') as f:
        has_menu = TESTER_MARK in f.read()
    if has_menu and not TESTER:
        sys.exit('в обычную сборку попало меню тестера (game/tester.py): архив не собран')
    if TESTER and not has_menu:
        sys.exit('в сборке для тестера нет меню тестера (game/tester.py): архив не собран')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    if os.path.exists(OUT):
        os.remove(OUT)
    n = 0
    total = 0
    readme = tester_readme() if TESTER else README_TXT
    with zipfile.ZipFile(OUT, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        # BOM нужен, чтобы «Блокнот» старых версий Windows верно показал кириллицу
        z.writestr(TOP + '/README.txt', (u'\ufeff' + readme.replace('\n', '\r\n')).encode('utf-8'))
        z.writestr(TOP + '/music/Как добавить песни.txt',
                   (u'\ufeff' + MUSIC_TXT.replace('\n', '\r\n')).encode('utf-8'))
        # запуск с графикой «Минимум» — если с шейдерами игра не открывается.  В самом файле только латиница:
        # так он не зависит от кодовой страницы Windows
        z.writestr(TOP + u'/Безопасный запуск.bat', SAFE_BAT.replace('@EXE@', APP + '.exe').encode('ascii'))
        for base, dirs, files in os.walk(BUILD):
            dirs.sort()
            for name in sorted(files):
                path = os.path.join(base, name)
                rel = os.path.relpath(path, BUILD).replace(os.sep, '/')
                z.write(path, TOP + '/' + rel)
                n += 1
                total += os.path.getsize(path)
    print('%s: %d файлов, %.1f МБ без сжатия, архив %.1f МБ' % (
        os.path.relpath(OUT, ROOT), n, total / 1e6, os.path.getsize(OUT) / 1e6))


if __name__ == '__main__':
    main()
