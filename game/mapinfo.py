# -*- coding: utf-8 -*-
"""Привязка текстур карты (assets/tex/map*.png) к мировым координатам.

Карт две: основная (Порт-Глухов с Заречьем и восточным берегом) и карта Зимогорска — городка пролога,
который лежит далеко на востоке и с основной картой никак не связан.
"""
MAP_CX = 335.0
MAP_CY = 340.0
MAP_HALF = 1100.0         # карта покрывает квадрат 2200 x 2200 м: остров, Заречье и восточный берег

NORTH_X0 = 2445.0         # всё, что восточнее этой черты, — Зимогорск (то же число — city.intro_x0)
NORTH_CX = 4230.0
NORTH_CY = 1560.0
NORTH_HALF = 640.0        # городок и петля тракта: квадрат 1280 x 1280 м


def region(x, y=0.0):
    """Карта, на которой лежит точка мира: (имя текстуры, центр x, центр y, полуразмер)."""
    if x > NORTH_X0:
        return ('map_north', NORTH_CX, NORTH_CY, NORTH_HALF)
    return ('map', MAP_CX, MAP_CY, MAP_HALF)


def world_to_uv(x, y):
    tex, cx, cy, half = region(x, y)
    return ((x - (cx - half)) / (2.0 * half), (y - (cy - half)) / (2.0 * half))
