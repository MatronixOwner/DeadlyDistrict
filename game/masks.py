"""Маски камер: что попадает в карты теней (см. gfx.py).

У камер, которые рисуют карты теней, свои маски.  Узел, скрытый для маски (NodePath.hide(маска)), в карту
не попадает — то есть тени не отбрасывает; на обычную картинку это не влияет, и тени на него ложатся
как раньше.  Так из карт убрано всё, от чего тени не бывает: это и правильнее (свечение фонаря тени не
даёт), и видеокарте вдвое меньше работы.
"""
from panda3d.core import BitMask32

SHADOW_NEAR = BitMask32.bit(5)              # ближняя карта: всё, что отбрасывает тень
SHADOW_FAR = BitMask32.bit(6)               # дальняя карта: только неподвижный город (машин и людей в ней нет)
NO_SHADOW = SHADOW_NEAR | SHADOW_FAR        # земля, дороги, наклейки, огни, вода, небо
